import { readFileSync, writeFileSync } from 'node:fs'

import { expect, it } from 'vitest'

import { garmentGuides } from '@/lib/guides'

const PATH = new URL('../lib/guide-outline.generated.ts', import.meta.url)

const outlines = Object.fromEntries(
  garmentGuides.map((g) => [g.garmentId, { steps: g.steps.map((s) => (s.tool ? { title: s.title, tool: s.tool } : { title: s.title })), pieces: g.pieces.length }]),
)
const file = `// Generated by \`npm run guide-outline\` from lib/guides.ts. Don't edit by hand.
import type { GuideOutline } from './types'

export const guideOutlines: Record<string, GuideOutline> = ${JSON.stringify(outlines, null, 2)}
`

it('the public outline matches the guides, and carries no instructions', () => {
  if (process.env.GENERATE_OUTLINE) writeFileSync(PATH, file)
  const current = readFileSync(PATH, 'utf8')
  expect(current, 'Run npm run guide-outline').toBe(file)
  expect(current).not.toContain('instruction')
  expect(current).not.toContain('topWidth')
})

it('every guide survives the trip from the server, with the same numbers for every size', async () => {
  const { packGuide, unpackGuide } = await import('@/lib/guide-wire')
  const { standardSizes } = await import('@/lib/data')
  const { allSizes } = await import('@/lib/sizes')
  for (const guide of garmentGuides) {
    const arrived = unpackGuide(JSON.parse(JSON.stringify(packGuide(guide))))
    expect(arrived.steps).toEqual(JSON.parse(JSON.stringify(guide.steps)))
    guide.pieces.forEach((piece, i) => {
      for (const size of allSizes) {
        const m = standardSizes[size]
        const dims = (p: typeof piece) => (typeof p.dims === 'function' ? p.dims(m) : p.dims)
        expect(dims(arrived.pieces[i])).toEqual(dims(piece))
      }
    })
  }
})
